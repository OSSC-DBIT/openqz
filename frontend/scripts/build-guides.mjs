// Build the user guides (docs/guides/*.md) into static pages served at /guides/*.html.
// Run: pnpm guides   (CI fails if the generated pages are out of date)
//
// ```mermaid blocks become pictures drawn beforehand by scripts/render-diagrams.mjs (pnpm
// guides:diagrams): a light and a dark SVG per diagram, shown with <picture>. The styles are a file
// (guides.css). No diagram script and no inline style run in the page, so the site's CSP needs no
// 'unsafe-inline'. This script draws nothing itself, so its output is the same on every machine.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { marked } from 'marked';
import { diagramHash } from './render-diagrams.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', '..', 'docs', 'guides');
const out = join(here, '..', 'public', 'guides');
const diagrams = join(out, 'diagrams');
mkdirSync(out, { recursive: true });

const escapeHtml = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const missing = [];

/** A text alternative for a flow diagram: its boxes and arrow labels, in order. */
function describe(source) {
  const labels = [];
  const box = /[\w-]+\s*(?:\(\[|\[\[|\[\(|\(\(|\[|\(|\{)"?([^\]\)\}"]+)"?(?:\]\)|\]\]|\)\]|\)\)|\]|\)|\})/g;
  const edge = /--\s*"([^"]+)"\s*-->|--\s+([^->"\n]+?)\s+-->/g;
  for (const line of source.split('\n')) {
    for (const m of line.matchAll(box)) labels.push(m[1].trim());
    for (const m of line.matchAll(edge)) labels.push((m[1] ?? m[2]).trim());
  }
  return [...new Set(labels.map((l) => l.replace(/<br\s*\/?>/gi, ', ')))].join('; ');
}

marked.use({
  renderer: {
    code({ text, lang }) {
      if (lang !== 'mermaid') return false;
      const hash = diagramHash(text);
      const light = join(diagrams, `${hash}-light.svg`);
      if (!existsSync(light) || !existsSync(join(diagrams, `${hash}-dark.svg`))) {
        missing.push(hash);
        return '';
      }
      const size = readFileSync(light, 'utf8').match(/<svg[^>]*? width="(\d+)" height="(\d+)"/);
      const [w, h] = size ? [size[1], size[2]] : ['800', '400'];
      return (
        `<figure class="diagram"><picture>` +
        `<source srcset="/guides/diagrams/${hash}-dark.svg" media="(prefers-color-scheme: dark)" />` +
        `<img src="/guides/diagrams/${hash}-light.svg" width="${w}" height="${h}" loading="lazy" alt="Flow diagram: ${escapeHtml(describe(text))}" />` +
        `</picture></figure>\n`
      );
    },
  },
});

const css = `/* generated by scripts/build-guides.mjs */
:root { --brand:#d6177f; --ink:#3b142a; --muted:#6b6880; --bg:#f6f5fb; --card:#fff; --line:#e6e4ef; }
@media (prefers-color-scheme: dark) { :root { --brand:#ff5cb0; --ink:#ecebf5; --muted:#a29fb8; --bg:#12111a; --card:#1c1a27; --line:#2c2a3a; } }
* { box-sizing: border-box; }
body { margin:0; background:var(--bg); color:var(--ink); font:16px/1.65 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif; }
main { max-width:760px; margin:0 auto; padding:24px 16px 64px; }
header { display:flex; align-items:center; gap:10px; margin-bottom:8px; }
header a { color:var(--brand); font-weight:700; text-decoration:none; }
h1 { font-size:1.9rem; line-height:1.2; } h2 { margin-top:2rem; border-bottom:1px solid var(--line); padding-bottom:.3rem; }
a { color:var(--brand); } code { background:var(--card); border:1px solid var(--line); border-radius:6px; padding:1px 5px; }
table { border-collapse:collapse; width:100%; display:block; overflow-x:auto; }
th, td { border:1px solid var(--line); padding:6px 10px; text-align:left; vertical-align:top; }
th { background:var(--card); }
blockquote { margin:1rem 0; padding:.6rem 1rem; border-left:4px solid var(--brand); background:var(--card); border-radius:8px; }
figure.diagram { margin:1.25rem 0; padding:12px; background:var(--card); border:1px solid var(--line); border-radius:12px; overflow-x:auto; text-align:center; }
figure.diagram img { max-width:100%; height:auto; }
footer { margin-top:3rem; padding-top:1rem; border-top:1px solid var(--line); color:var(--muted); font-size:.9rem; }
`;
writeFileSync(join(out, 'guides.css'), css);

const page = (title, body) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${title} | OpenQZ</title>
<link rel="stylesheet" href="/guides/guides.css" />
</head>
<body><main>
<header><a href="/login">&larr; OpenQZ</a></header>
${body}
<footer><a href="/privacy">Privacy Policy</a> | <a href="mailto:osscdbit@gmail.com">osscdbit@gmail.com</a></footer>
</main>
</body>
</html>
`;

const files = readdirSync(src).filter((f) => f.endsWith('.md'));
for (const f of files) {
  const md = readFileSync(join(src, f), 'utf8');
  const title = (md.match(/^#\s+(.+)$/m) || [, basename(f, '.md')])[1];
  const html = marked.parse(md, { gfm: true });
  writeFileSync(join(out, basename(f, '.md') + '.html'), page(title, html));
  console.log(`guides: ${f} -> public/guides/${basename(f, '.md')}.html`);
}
if (missing.length) {
  console.error(`guides: ${missing.length} diagram(s) not drawn yet (${missing.join(', ')}): run pnpm guides:diagrams`);
  process.exit(1);
}
